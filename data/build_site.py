"""BUILD the deployable course site, in every locale.

Run:  python3 build_site.py

Three jobs:

  1. NAVIGATION. Injects a slim nav bar into every page, between idempotent
     markers, so the build can be re-run without duplicating anything. The bar
     carries home, this page's position, its neighbours by name, and a language
     switcher.

     The nav lives in its OWN stylesheet. Six of the twelve English pages predate
     page.css and carry inline <style> blocks instead, so anything appended to
     page.css would silently miss half the site.

  2. LOCALES. English pages live at the repository root; a translation lives in
     <code>/ (e.g. ru/). Only pages that have actually been translated go into
     that locale's output. Its contents page links plainly to `x.html`, and this
     build REWRITES that to `../x.html` when no translation exists yet, so an
     untranslated entry falls back to the English page instead of 404ing. That
     rewrite is why translating a page later needs no bookkeeping: drop the file
     in ru/ and the link stops being rewritten.

  3. A CLEAN docs/. Copies each page plus only the assets that page actually
     references, resolved from its own <script src> and <link href> tags. The
     repository holds a 26 MB download cache, the measurement scripts and sixteen
     verification scripts -- none of which may ship. The rule is an ALLOWLIST
     built from the pages themselves, not a denylist of things to skip, because a
     denylist silently ships whatever it forgot.

     Each locale directory is SELF-CONTAINED -- it gets its own copy of the
     assets -- so every asset link stays flat and no page needs `../` to load a
     stylesheet. At ~580 KB a copy that is a trivial price for the simplicity.

GitHub Pages can publish a branch's root or /docs and nothing else, which is why
the output directory is called docs/. The name is that convention, not a
description.
"""
from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
OUT = ROOT / "docs"

NAV_BEGIN = "<!-- NAV:BEGIN generated by data/build_site.py — do not hand-edit -->"
NAV_END = "<!-- NAV:END -->"

FORBIDDEN = re.compile(r"(^|/)(\.attic|data|docs|dist|__pycache__)(/|$)|\.py$")

# Every locale the site is built in. `src` is the source directory relative to
# the repository root; `out` is the directory inside docs/. English is first and
# is the fallback for anything a translation has not covered yet.
LOCALES = [
    dict(code="en", label="EN", src=".", out=".", lang="en",
         count="{n} visuals · every figure checked against its data",
         start="start", of="{i} of {n}", home="UDJ"),
    dict(code="ru", label="RU", src="ru", out="ru", lang="ru",
         count="{n} визуализаций · каждая цифра сверена с данными",
         start="начать", of="{i} из {n}", home="UDJ"),
]


def src_dir(loc: dict) -> Path:
    return ROOT if loc["src"] == "." else ROOT / loc["src"]


def out_dir(loc: dict) -> Path:
    return OUT if loc["out"] == "." else OUT / loc["out"]


# --------------------------------------------------------------- the manifest
def manifest(loc: dict) -> list[dict]:
    """The running order, read from that locale's own contents page."""
    p = src_dir(loc) / "index.html"
    if not p.exists():
        raise SystemExit(f"{loc['code']}: no index.html in {p.parent}")
    s = p.read_text(encoding="utf-8")
    out = []
    for m in re.finditer(
        r'<li><a href="(?:\.\./)?([a-z]+\.html)">\s*'
        r'<span class="n">([^<]+)</span>\s*'
        r'<span class="t">([^<]+?)\s*<span class="d">',
        s,
    ):
        out.append(dict(href=m.group(1), num=m.group(2).strip(),
                        title=re.sub(r"\s+", " ", m.group(3)).strip()))
    if not out:
        raise SystemExit(f"{loc['code']}: could not read the running order")
    return out


